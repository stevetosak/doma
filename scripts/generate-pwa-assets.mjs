// Regenerates every PWA / browser icon and the iOS splash-screen set from
// one source drawing (public/doma-icon.svg, mirrored from brand/doma-icon.svg).
//
//   npm run generate:pwa-assets
//
// Outputs, all into public/:
//   favicon.ico, apple-touch-icon-180x180.png,
//   pwa-64x64 / 192x192 / 512x512.png, maskable-icon-512x512.png,
//   apple-splash-portrait-*.png (one per iOS device width)
//
// Portrait only: doma is a phone-first PWA held upright; a landscape cold
// launch is rare and falls back to the manifest background_color, which is
// the same colour the splash uses anyway. Light only: the splash ground is
// identical in both themes, so a dark variant would be a byte-for-byte dupe.
//
// It also writes src/core/pwa/apple-splash-links.ts — the <link rel=
// "apple-touch-startup-image"> list, consumed by __root.tsx. We build that
// file ourselves rather than paste the generator's HTML because the
// generator (v1.0.2) prints hrefs with a `-light-` infix its own PNG writer
// omits when dark splashes are off; we normalise that here.

import { execFileSync } from 'node:child_process'
import { existsSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const publicDir = resolve(root, 'public')
const linksFile = resolve(root, 'src/core/pwa/apple-splash-links.ts')

const stdout = execFileSync(
  'npx',
  ['pwa-assets-generator', '--config', 'pwa-assets.config.ts'],
  { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] },
)

// Drop the landscape splash PNGs the generator always emits.
let removed = 0
for (const name of readdirSync(publicDir)) {
  if (name.startsWith('apple-splash-landscape-')) {
    rmSync(resolve(publicDir, name))
    removed += 1
  }
}

const seen = new Set()
const links = []
const linkRe =
  /<link rel="apple-touch-startup-image" media="([^"]+)" href="([^"]+)">/g
for (const match of stdout.matchAll(linkRe)) {
  const media = match[1]
  const href = match[2].replace('-light-', '-')
  if (href.includes('apple-splash-landscape-')) continue
  if (seen.has(href)) continue
  seen.add(href)
  if (!existsSync(resolve(publicDir, href.replace(/^\//, '')))) {
    throw new Error(`splash link points at a missing file: ${href}`)
  }
  links.push({ media, href })
}

if (links.length === 0) {
  throw new Error(
    'no apple-touch-startup-image links parsed from generator output',
  )
}

writeFileSync(
  linksFile,
  `// GENERATED by scripts/generate-pwa-assets.mjs — do not edit by hand.\n` +
    `// iOS PWA splash screens. Spread into the root route's head links.\n\n` +
    `export const appleSplashLinks: ReadonlyArray<{\n` +
    `  rel: 'apple-touch-startup-image'\n` +
    `  media: string\n` +
    `  href: string\n` +
    `}> = [\n` +
    links
      .map(
        (l) =>
          `  { rel: 'apple-touch-startup-image', media: ${JSON.stringify(
            l.media,
          )}, href: ${JSON.stringify(l.href)} },`,
      )
      .join('\n') +
    `\n]\n`,
)

// Match the repo's prettier config so `npm run check` stays green.
execFileSync('npx', ['prettier', '--write', linksFile], {
  cwd: root,
  stdio: 'inherit',
})

console.log(
  `\n✔ ${links.length} portrait splash screens (removed ${removed} landscape) → src/core/pwa/apple-splash-links.ts`,
)
